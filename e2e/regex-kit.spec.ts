test('desglosa tokens y transforma coincidencias sin cambiar el texto hasta aplicar', async ({ page }) => {
  await page.goto('tools/regex-kit')
  const pattern = page.getByRole('textbox', { name: 'Patrón', exact: true })
  const text = page.getByRole('textbox', { name: 'Texto de prueba', exact: true })
  await pattern.fill('(?<letra>[a-z])([0-9]+)')
  await text.fill('a12 b34')
  const breakdown = page.locator('.token-breakdown')
  await expect(breakdown.getByRole('heading', { name: 'Grupo nombrado', exact: true })).toBeVisible()
  await expect(breakdown.getByRole('heading', { name: 'Cierre de grupo', exact: true })).toHaveCount(2)
  await expect(breakdown.getByRole('heading', { name: 'Una o más veces', exact: true })).toBeVisible()

  await page.getByRole('checkbox', { name: 'Activar transformación' }).check()
  const operation = page.getByRole('combobox', { name: 'Operación' })
  const substitute = page.getByRole('textbox', { name: 'Texto de sustitución' })
  const result = page.getByRole('textbox', { name: 'Resultado de la transformación' })
  await substitute.fill('$2:$<letra> $$ $&')
  await expect(result).toHaveValue('12:a $ a12 34:b $ b34')
  await operation.selectOption('literal')
  await expect(result).toHaveValue('$2:$<letra> $$ $& $2:$<letra> $$ $&')
  await operation.selectOption('upper')
  await expect(result).toHaveValue('A12 B34')
  await expect(text).toHaveValue('a12 b34')
  await page.getByRole('button', { name: 'Usar como texto de prueba' }).click()
  await expect(text).toHaveValue('A12 B34')
  await pattern.fill('^a{2,3}?$')
  await expect(breakdown.getByRole('heading', { name: 'Repetición contada · mínima' })).toBeVisible()
  await expect(breakdown.getByRole('heading', { name: 'Inicio', exact: true })).toBeVisible()
})

test('transforma más coincidencias de las que muestra el inspector y limita salidas grandes', async ({ page }) => {
  await page.goto('tools/regex-kit')
  await page.getByRole('textbox', { name: 'Patrón', exact: true }).fill('a')
  await page.getByRole('textbox', { name: 'Texto de prueba', exact: true }).fill('a'.repeat(301))
  await page.getByRole('checkbox', { name: 'Activar transformación' }).check()
  const substitute = page.getByRole('textbox', { name: 'Texto de sustitución' })
  const result = page.getByRole('textbox', { name: 'Resultado de la transformación' })
  await substitute.fill('b')
  await expect(result).toHaveValue('b'.repeat(301))
  await substitute.fill('x'.repeat(1000))
  await expect(page.getByText(/El resultado supera el límite/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Copiar resultado' })).toBeDisabled()
})

test('pliega y redistribuye los paneles de patrón y tokens en escritorio y móvil', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('tools/regex-kit')
  const patternPane = page.locator('.pattern-pane')
  const tokensPane = page.locator('.tokens-pane')
  const editorToggle = patternPane.getByRole('button', { name: 'Patrón', exact: true })
  const tokensToggle = tokensPane.getByRole('button', { name: 'Desglose léxico de tokens en tiempo real', exact: true })
  const editor = page.getByRole('textbox', { name: 'Patrón', exact: true })
  const tokens = page.locator('.token-breakdown')

  await editor.fill('^(?<n>[0-9]+)$')
  const bothOpen = (await patternPane.boundingBox())!
  expect((await tokensPane.boundingBox())!.x).toBeGreaterThan(bothOpen.x)
  await tokensToggle.press('Enter')
  await expect(tokensToggle).toHaveAttribute('aria-expanded', 'false')
  await expect(tokens).toBeHidden()
  expect((await patternPane.boundingBox())!.width).toBeGreaterThan(bothOpen.width * 1.5)
  expect((await tokensPane.boundingBox())!.width).toBeLessThan(55)

  await editorToggle.click()
  await expect(editor).toBeHidden()
  await tokensToggle.click()
  await expect(tokens.getByRole('heading', { name: 'Grupo nombrado', exact: true })).toBeVisible()
  expect((await patternPane.boundingBox())!.width).toBeLessThan(55)
  await editorToggle.click()
  await expect(editor).toHaveValue('^(?<n>[0-9]+)$')

  await page.setViewportSize({ width: 390, height: 850 })
  const mobilePattern = (await patternPane.boundingBox())!
  expect((await tokensPane.boundingBox())!.y).toBeGreaterThanOrEqual(mobilePattern.y + mobilePattern.height)
  await tokensToggle.click()
  await expect(tokens).toBeHidden()
  expect(Math.round((await tokensPane.boundingBox())!.width)).toBe(Math.round(mobilePattern.width))
})
