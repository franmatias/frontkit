import { expect, test } from '@playwright/test'

test('carga plantillas, resalta grupos y copia el patrón y el constructor', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('tools/regex-kit')
  await expect(page.getByRole('heading', { name: 'Expresiones regulares', exact: true })).toBeVisible()
  const presets = page.getByLabel('Plantillas')
  const pattern = page.getByRole('textbox', { name: 'Patrón', exact: true })
  await expect(page.getByText('Grupo «usuario»', { exact: true }).first()).toBeVisible()
  await expect(page.locator('mark.match-1').first()).toHaveText('aula')
  await expect(page.locator('mark.match-2').first()).toHaveText('example.org')
  await expect(page.locator('.pattern pre .group').first()).toHaveText('(?<usuario>')
  await expect(page.locator('.pattern pre .quantifier').first()).toHaveText('+')
  await expect(page.locator('.pattern pre .escape').first()).toHaveText('\\w')
  for (const [preset, matches] of [['dni', '2'], ['iban', '1'], ['date', '2']] as const) {
    await presets.selectOption(preset)
    await expect(page.getByRole('status').filter({ hasText: /^(\d+) coincidencia/ })).toHaveText(new RegExp('^' + matches + ' coincidencia'))
  }
  const current = await pattern.inputValue()
  await page.getByRole('button', { name: 'Copiar patrón', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(current)
  await page.getByRole('button', { name: 'Copiar JavaScript / TypeScript', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText()))
    .toBe('const regex = new RegExp(' + JSON.stringify(current) + ', "g");')
})

test('trata coincidencias vacías, muestra errores y recupera el editor tras el timeout', async ({ page }) => {
  await page.goto('tools/regex-kit')
  const pattern = page.getByRole('textbox', { name: 'Patrón', exact: true })
  const input = page.getByRole('textbox', { name: 'Texto de prueba' })
  await pattern.fill('(?=.)')
  await input.fill('😀a')
  await page.getByLabel('u · Unicode', { exact: true }).check()
  await expect(page.locator('.inspector summary')).toHaveCount(2)
  await expect(page.locator('.inspector summary').nth(1)).toContainText('[2, 2)')
  await page.getByLabel('v · Conjuntos Unicode', { exact: true }).check()
  await expect(page.getByLabel('u · Unicode', { exact: true })).not.toBeChecked()
  await expect(page.locator('.inspector summary')).toHaveCount(2)
  await pattern.fill('(')
  await expect(page.getByRole('alert')).toContainText('Expresión no válida')
  await pattern.fill('^([a]+)+$')
  await input.fill('a'.repeat(60) + '!')
  await expect(page.getByRole('alert')).toContainText('Tiempo límite superado')
  await pattern.fill('!$')
  await expect(page.locator('mark')).toHaveText('!')
  await expect(page.locator('.inspector summary')).toHaveCount(1)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('g · Todas las coincidencias', { exact: true }).uncheck()
  await pattern.fill('a(?<opcional>z)?')
  await input.fill('a az')
  await expect(page.locator('.inspector summary')).toHaveCount(1)
  await expect(page.getByText('Grupo «opcional»')).toBeVisible()
  await expect(page.getByText('Sin captura', { exact: true })).toHaveCount(2)
})

test('guarda, edita, carga y elimina plantillas personales entre recargas', async ({ page }) => {
  await page.goto('tools/regex-kit')
  await page.getByLabel('Plantillas', { exact: true }).selectOption('hex')
  await expect(page.locator('.test-panel [role=status]')).toHaveText('4 coincidencias')
  const library = page.getByText('Mis plantillas', { exact: true })
  await library.click()
  await page.getByRole('button', { name: 'Guardar plantilla actual' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Nombre' }).fill('Mis colores')
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(dialog).toHaveCount(0)

  await page.reload()
  await page.locator('.regex-templates summary').click()
  await page.getByRole('button', { name: 'Editar Mis colores' }).click()
  await expect(dialog.getByRole('textbox', { name: 'Patrón de la plantilla' })).toHaveValue(/^#/)
  await dialog.getByRole('textbox', { name: 'Nombre' }).fill('Dígitos')
  await dialog.getByRole('textbox', { name: 'Patrón de la plantilla' }).fill('\\d+')
  await dialog.getByRole('textbox', { name: 'Texto de prueba de la plantilla' }).fill('A1 B22')
  await dialog.getByRole('checkbox', { name: 'g en plantilla · Todas las coincidencias' }).uncheck()
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Cargar Dígitos' })).toBeVisible()

  await page.reload()
  await page.locator('.regex-templates summary').click()
  await page.getByRole('button', { name: 'Cargar Dígitos' }).click()
  await expect(page.getByRole('textbox', { name: 'Texto de prueba', exact: true })).toHaveValue('A1 B22')
  await expect(page.locator('.test-panel [role=status]')).toHaveText('1 coincidencia')
  page.once('dialog', confirmation => confirmation.accept())
  await page.getByRole('button', { name: 'Eliminar Dígitos' }).click()
  await expect(page.getByRole('button', { name: 'Cargar Dígitos' })).toHaveCount(0)
  await page.reload()
  await page.locator('.regex-templates summary').click()
  await expect(page.getByRole('button', { name: 'Cargar Dígitos' })).toHaveCount(0)
})

